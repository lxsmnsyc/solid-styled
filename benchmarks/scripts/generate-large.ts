// Writes fixtures/large.tsx: 50 components with a mix of `css` templates and
// `<style jsx>` elements, using interpolations, nesting, `:global`,
// `@keyframes` and `@media`. The output is deterministic, so the fixture is
// committed and only regenerated when this script changes.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const COMPONENTS = 50;
const COLORS = ['#1f6feb', '#d1242f', '#1a7f37', '#9a6700', '#8250df', '#bf3989'];
const TAGS = ['section', 'article', 'aside', 'div', 'header', 'footer'];

function renderSheet(index: number): string {
  const color = COLORS[index % COLORS.length];
  const lines: string[] = [];

  // Every component has a few plain and nested rules.
  lines.push(
    `    .card-${index} {`,
    `      display: flex;`,
    `      gap: ${(index % 4) + 1}rem;`,
    `      padding: \${props.padding}px;`,
    `      color: \${color()};`,
    `      border: 1px solid ${color};`,
    `      background-color: color-mix(in srgb, ${color} 10%, white);`,
    `      & > .title {`,
    `        font-size: 1.25rem;`,
    `        font-weight: 600;`,
    `      }`,
    `      &:hover .title {`,
    `        text-decoration: underline;`,
    `      }`,
    `    }`,
    `    .body p + p {`,
    `      margin-top: 0.5rem;`,
    `    }`,
    `    ul > li::marker {`,
    `      color: ${color};`,
    `    }`,
  );

  if (index % 2 === 0) {
    lines.push(
      `    :global(.theme-dark) .card-${index} {`,
      `      background-color: #0d1117;`,
      `    }`,
      `    .body :global(a[href^='http']) {`,
      `      color: #0969da;`,
      `    }`,
    );
  }
  if (index % 3 === 0) {
    lines.push(
      `    @keyframes pulse-${index} {`,
      `      from { opacity: 0.4; transform: scale(0.98); }`,
      `      to { opacity: 1; transform: scale(1); }`,
      `    }`,
      `    .badge {`,
      `      animation: pulse-${index} \${props.duration}ms ease-in-out infinite alternate;`,
      `    }`,
    );
  }
  if (index % 4 === 0) {
    lines.push(
      `    @media (max-width: ${600 + index * 4}px) {`,
      `      .card-${index} {`,
      `        flex-direction: column;`,
      `      }`,
      `      .title {`,
      `        font-size: 1rem;`,
      `      }`,
      `    }`,
      `    @media (prefers-reduced-motion: reduce) {`,
      `      .badge {`,
      `        animation: none;`,
      `      }`,
      `    }`,
    );
  }
  if (index % 5 === 0) {
    lines.push(
      `    @global {`,
      `      body.modal-open-${index} {`,
      `        overflow: hidden;`,
      `      }`,
      `    }`,
    );
  }
  return lines.join('\n');
}

function renderComponent(index: number): string {
  const tag = TAGS[index % TAGS.length];
  const sheet = renderSheet(index);
  const head = [
    `export function Card${index}(props: { title: string; padding: number; duration: number; items: string[] }) {`,
    `  const [color, setColor] = createSignal('${COLORS[index % COLORS.length]}');`,
  ];
  const body = [
    `    <${tag} class="card-${index}" onClick={() => setColor('${COLORS[(index + 1) % COLORS.length]}')}>`,
    `      <h2 class="title">{props.title}</h2>`,
    `      <span class="badge">${index}</span>`,
    `      <div class="body">`,
    `        <p>First paragraph of card ${index}.</p>`,
    `        <p>Second paragraph with <a href="https://example.com/${index}">a link</a>.</p>`,
    `        <ul>`,
    `          <For each={props.items}>{(item) => <li>{item}</li>}</For>`,
    `        </ul>`,
    `      </div>`,
  ];

  // One in three components uses `<style jsx>` instead of the `css` tag.
  if (index % 3 === 1) {
    return [
      ...head,
      `  return (`,
      ...body,
      `      <style jsx>{\``,
      sheet,
      `      \`}</style>`,
      `    </${tag}>`,
      `  );`,
      `}`,
    ].join('\n');
  }
  return [
    ...head,
    `  css\``,
    sheet,
    `  \`;`,
    `  return (`,
    ...body,
    `    </${tag}>`,
    `  );`,
    `}`,
  ].join('\n');
}

function generate(): string {
  const parts = [
    `// Generated by benchmarks/scripts/generate-large.ts. Do not edit.`,
    `import { css } from 'solid-styled';`,
    `import { For, createSignal } from 'solid-js';`,
  ];
  for (let index = 0; index < COMPONENTS; index += 1) {
    parts.push(renderComponent(index));
  }
  return `${parts.join('\n\n')}\n`;
}

writeFileSync(fileURLToPath(new URL('../fixtures/large.tsx', import.meta.url)), generate());
